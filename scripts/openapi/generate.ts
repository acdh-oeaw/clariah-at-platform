import * as fs from "node:fs/promises";
import * as path from "node:path";

import { createUrl, log } from "@acdh-oeaw/lib";

import { env } from "#/configs/env.config.ts";

/**
 * `openapi-typescript` prints its output with the TypeScript compiler's AST API, which is not (yet) exposed by
 * TypeScript v7. We therefore run the generator via `pnpx`, in an environment which is pinned to TypeScript v6, and
 * isolated from the TypeScript version used by the app.
 *
 * Once TypeScript v7 ships the factory and printer APIs, we can go back to importing `openapi-typescript` directly.
 */
const versions = {
	"openapi-typescript": "7.13.0",
	typescript: "6.0.3",
};

const baseUrl = env.NEXT_PUBLIC_API_BASE_URL;
const pathname = env.NEXT_PUBLIC_API_OPENAPI_PATHNAME;

const outputFilePath = "./lib/openapi/types.ts";
const cacheTagsOutputFilePath = "./lib/openapi/cache-tags.ts";

function generateTypes(url: URL): void {
	const { exitCode, signalCode, success } = Bun.spawnSync(
		[
			"pnpx",
			...Object.entries(versions).map(([name, version]) => `--package=${name}@${version}`),
			"openapi-typescript",
			String(url),
			"--output",
			outputFilePath,
		],
		{ stdout: "inherit", stderr: "inherit" },
	);

	if (!success) {
		/** `exitCode` is `null` when the process was killed by a signal. */
		const reason = signalCode != null ? `signal ${signalCode}` : `status code ${String(exitCode)}`;

		throw new Error(`Generator exited with ${reason}.`);
	}
}

interface OpenApiSchema {
	enum?: Array<string>;
}

interface OpenApiOperation {
	operationId?: string;
	"x-cache-tags"?: Array<string>;
	responses?: Record<string, { content?: Record<string, unknown> }>;
}

interface OpenApiSpec {
	components?: { schemas?: Record<string, OpenApiSchema> };
	paths?: Record<string, Record<string, OpenApiOperation>>;
}

/** Mirrors `JsonBody<K>` in `lib/data/api-client.ts`: only a `200` response with an `application/json` body counts. */
function isJsonOperation(operation: OpenApiOperation): boolean {
	return operation.responses?.["200"]?.content?.["application/json"] != null;
}

/**
 * The api declares a `CacheTag` enum — every slice of data it serves — plus `x-cache-tags` on each operation: the
 * entity-type tags that operation's response transitively depends on, including embedded/joined data from other entity
 * types (e.g. a person's response embeds their governance-body affiliations). The `revalidate` webhook delivers exactly
 * this `CacheTag` vocabulary too (see `CacheTag`'s own description in the spec). `openapi-typescript` carries the
 * enum's _type_ into `lib/openapi/types.ts`, but not a runtime value, and it drops vendor extensions like
 * `x-cache-tags` entirely — so both are fetched and written out here instead, consumed by `lib/data/api-cache.ts`
 * (tagging cached responses) and `app/(api)/api/revalidate/route.ts` (validating the webhook payload).
 */
async function generateCacheTags(url: URL): Promise<void> {
	const response = await fetch(url);

	if (!response.ok) {
		throw new Error(`Failed to fetch the OpenAPI schema: ${String(response.status)} ${response.statusText}`);
	}

	const spec = (await response.json()) as OpenApiSpec;

	const cacheTagEnum = spec.components?.schemas?.CacheTag?.enum;
	if (cacheTagEnum == null) {
		throw new Error('The OpenAPI schema no longer declares a "CacheTag" enum schema.');
	}
	const cacheTags = cacheTagEnum.toSorted((a, b) => a.localeCompare(b));

	const operationCacheTags: Record<string, ReadonlyArray<string>> = {};

	for (const methods of Object.values(spec.paths ?? {})) {
		for (const operation of Object.values(methods)) {
			if (operation.operationId == null || operation["x-cache-tags"] == null || !isJsonOperation(operation)) {
				continue;
			}

			operationCacheTags[operation.operationId] = operation["x-cache-tags"];
		}
	}

	const operationEntries = Object.entries(operationCacheTags)
		.toSorted(([a], [b]) => a.localeCompare(b))
		.map(([operationId, tags]) => `\t${operationId}: ${JSON.stringify(tags)},`)
		.join("\n");

	const content = `// Generated by \`scripts/openapi/generate.ts\` from the api's OpenAPI spec (the \`CacheTag\` enum and \`x-cache-tags\` per operation). Do not edit by hand.
import type { CacheTag, JsonOperationId } from "#/lib/data/api-client.ts";

/** The \`CacheTag\` vocabulary as a runtime value, for validating the revalidation webhook payload. */
export const cacheTags: ReadonlyArray<CacheTag> = ${JSON.stringify(cacheTags)};

export const operationCacheTags: Record<JsonOperationId, ReadonlyArray<CacheTag>> = {
${operationEntries}
};
`;

	await fs.writeFile(cacheTagsOutputFilePath, content);

	Bun.spawnSync(["pnpx", "oxfmt", "--write", cacheTagsOutputFilePath], { stdout: "inherit", stderr: "inherit" });
}

async function generate(): Promise<void> {
	const url = createUrl({ baseUrl, pathname });

	await fs.mkdir(path.dirname(outputFilePath), { recursive: true });

	generateTypes(url);
	await generateCacheTags(url);
}

generate()
	// oxlint-disable-next-line promise/always-return
	.then(() => {
		log.success("Successfully generated API types from OpenAPI schema.");
	})
	.catch((error: unknown) => {
		log.error("Failed to generate API types from OpenAPI schema.\n", error);
	});
